"""The skills reference page, generated from the skills that ship in the package.

``docs/agents/skills_reference.md`` is :func:`render_reference`'s output, and a test
keeps the two identical, so the page cannot drift from the skills. For each skill the
page shows its name and title, when to use it (the front matter's ``description``), its
opening lines, the steps it follows (its numbered headings) and its worked example,
copied as it is. The worked example is the part the test suite runs
(:mod:`sensoryforge.testing.skill_examples`), so what the page shows is what passes.

Regenerate the page after changing a skill::

    python -m sensoryforge.agents.reference docs/agents/skills_reference.md

The module needs only the standard library.

Example:
    >>> text = render_reference()
    >>> "## Workflow" in text and "sensoryforge-setup" in text
    True

Topic: agents
Tests: tests/unit/test_agent_docs.py
Entry points: render_reference, render_skill_section, CHAIN_ORDER
Pinned by: docs/agents/skills_reference.md
Do not change without: regenerating the page in the same commit (the test fails
    otherwise); a skill's worked example is copied, never rewritten.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path
from typing import List, Optional, Sequence, Tuple

from sensoryforge.agents.install import packaged_skills

CHAIN_ORDER = (
    "sensoryforge-setup",
    "sensoryforge-design-and-plan",
    "sensoryforge-design-world",
    "sensoryforge-ground-assumptions",
    "sensoryforge-build-dataset",
    "sensoryforge-run-simulation",
    "sensoryforge-evaluate",
    "sensoryforge-diagnose",
    "sensoryforge-interpret-report",
    "sensoryforge-workflow",
    "sensoryforge-extend-pipeline",
)
"""The order the page lists the skills in: the usual chain. A skill not named here
follows, by name."""

_FENCE = re.compile(r"^\s*(```|~~~)")
_STEP = re.compile(r"^\d+\.\s+")

_INTRO = """\
# Skills Reference

This page is for anyone who wants to see what each SensoryForge skill does before an
agent runs it. It is generated from the skill files that ship in the package
(`sensoryforge/agents/skills/<name>/SKILL.md`), so it says what the installed skills
say. For each skill: when an agent picks it, the steps it follows, and its worked
example.

The worked examples are not illustrations. The test suite writes each example's files
into an empty folder and runs its commands, checking what each prints (`# prints:`) and
its exit code (`# exit:`), so an example that drifts from the code fails before a
release. To run one yourself, copy its files into a new folder and run its commands
there.

You do not name a skill to use it: say what you want and the agent picks the skill
whose purpose matches what you mean. The short table is in
[Skills for a Coding Agent](../user_guide/agent_skills.md); how the skills work with
you is set in the [setup](../user_guide/agent_setup.md).

<!-- Generated by `python -m sensoryforge.agents.reference` from the packaged skills.
Do not edit: change the skill, then run the command again. -->
"""


def _split(text: str) -> Tuple[dict, List[str]]:
    """``(front matter, body lines)`` of a skill.

    Raises:
        ValueError: If the text has no closed front matter.
    """
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError("a skill must start with front matter (---)")
    try:
        end = lines.index("---", 1)
    except ValueError:
        raise ValueError("a skill's front matter is not closed (---)") from None
    meta = {}
    for line in lines[1:end]:
        key, sep, value = line.partition(":")
        if sep:
            meta[key.strip()] = value.strip()
    return meta, lines[end + 1 :]


def _sections(
    body: Sequence[str],
) -> Tuple[str, List[str], List[Tuple[str, List[str]]]]:
    """``(title, opening lines, [(heading, lines), ...])`` of a skill body.

    Headings inside a fenced block (a ``# file:`` line in YAML, say) are not headings.
    """
    title, opening = "", []
    sections: List[Tuple[str, List[str]]] = []
    in_fence = False
    for line in body:
        if _FENCE.match(line):
            in_fence = not in_fence
        if not in_fence and line.startswith("# ") and not title:
            title = line[2:].strip()
            continue
        if not in_fence and line.startswith("## "):
            sections.append((line[3:].strip(), []))
            continue
        (sections[-1][1] if sections else opening).append(line)
    return title, opening, sections


def _trim(lines: Sequence[str]) -> List[str]:
    out = list(lines)
    while out and not out[0].strip():
        out.pop(0)
    while out and not out[-1].strip():
        out.pop()
    return out


def render_skill_section(name: str, text: str) -> str:
    """One skill's part of the page.

    Args:
        name: The skill's folder name (``sensoryforge-<verb>``).
        text: Its ``SKILL.md``.

    Returns:
        Markdown: a level-2 heading with the skill's title, then when to use it, its
        opening lines, its steps and its worked example.

    Raises:
        ValueError: If the skill has no front matter or no worked example.
    """
    meta, body = _split(text)
    title, opening, sections = _sections(body)
    example: Optional[List[str]] = None
    steps, also = [], []
    for heading, lines in sections:
        if heading == "Worked example":
            example = _trim(lines)
        elif _STEP.match(heading):
            steps.append(_STEP.sub("", heading))
        else:
            also.append(heading)
    if example is None:
        raise ValueError(f"{name}: a skill must end with a 'Worked example' section")
    out = [f"## {title or name}", "", f"`{name}`", ""]
    out += [f"**When an agent uses it.** {meta.get('description', '')}", ""]
    out += _trim(opening) + [""]
    out += ["**Steps.** " + "; ".join(steps) + "." if steps else "", ""]
    if also:
        out += ["**Also covers.** " + "; ".join(also) + ".", ""]
    out += ["### Worked example", ""] + example + [""]
    return "\n".join(out)


def render_reference() -> str:
    """The whole page: the introduction, then every packaged skill in chain order."""
    skills = dict(packaged_skills())
    order = [n for n in CHAIN_ORDER if n in skills]
    order += sorted(n for n in skills if n not in CHAIN_ORDER)
    parts = [_INTRO]
    for name in order:
        parts.append(render_skill_section(name, skills[name].read_text("utf-8")))
    return "\n".join(parts).rstrip("\n") + "\n"


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Write the page to the path given, or print it."""
    args = list(sys.argv[1:] if argv is None else argv)
    text = render_reference()
    if args:
        Path(args[0]).write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

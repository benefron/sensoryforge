@pytest.mark.parametrize("target", sorted(FOLDERS))
def test_every_file_is_valid_headed_and_the_source_unchanged(tmp_path, target):
    written = ins.install(tmp_path, target)
    spec = ins.EXPORT_TARGETS[target]
    base = tmp_path / spec.skills_dir
    assert {s for _, s in written} == {"added"}
    names = [n for n, _ in ins.packaged_skills()]
    assert len(names) >= 10
    for name, source in ins.packaged_skills():
        text = (base / name / "SKILL.md").read_text(encoding="utf-8")
        meta, body = _front(text)
        # The open Agent Skills format, which every target's tool reads.
        assert set(meta) == {"name", "description"}, "only the fields all tools share"
        assert meta["name"] == name and NAME.match(name) and len(name) <= 64
        assert 1 <= len(meta["description"]) <= 1024, name
        # Front matter is first and the header comes right after it; taking the
        # header out gives the source file back, byte for byte.
        header = f"\n<!-- {HEADER} {target}`"
        assert header in text
        line = text[text.index(header) : text.index("-->\n", text.index(header)) + 4]
        assert text.replace(line, "", 1) == source.read_text(encoding="utf-8")
        assert _front(source.read_text(encoding="utf-8"))[0] == meta
    glossary = (base / ins.GLOSSARY_NAME).read_text(encoding="utf-8")
    assert glossary.startswith("<!-- " + HEADER)
    assert glossary.endswith(ins.packaged_glossary().read_text(encoding="utf-8"))
    extra = {p.name for p in base.iterdir()} - set(names) - {ins.GLOSSARY_NAME}
    assert extra == ({ins.INDEX_NAME} if spec.index else set())
    assert {p.name for p in tmp_path.iterdir()} == {spec.skills_dir.parts[0]}


def test_the_generic_readme_says_what_to_read_and_lists_every_skill(tmp_path):
    ins.install(tmp_path, "generic")
    assert ins.INDEX_NAME == "README.md"
    index = (tmp_path / "sensoryforge-agents" / ins.INDEX_NAME).read_text("utf-8")
    assert index.startswith("<!-- " + HEADER)
    order = [
        index.index(s) for s in ("This file.", "agents brief`: how", "glossary.md`:")
    ]
    assert order == sorted(order), "the files to read, in order"
    assert "agents prompt generic" in index and "agents prompt instructions" in index
    assert "agents instructions --target generic --file FILE --write" in index
    for name, path in ins.packaged_skills():
        first = _front(path.read_text("utf-8"))[0]["description"].split(". ")[0]
        assert f"[{name}]({name}/SKILL.md) | {first.rstrip('.')}." in index
    assert "sensoryforge agents brief" in index



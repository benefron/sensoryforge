# ------------------------------------------------------------------- staleness


@pytest.mark.parametrize("target", sorted(FOLDERS))
def test_check_finds_a_stale_or_missing_file_and_writes_nothing(tmp_path, target):
    assert {s for _, s in ins.check(tmp_path, target)} == {"missing"}
    assert not any(tmp_path.iterdir()), "check must not write"
    ins.install(tmp_path, target)
    assert {s for _, s in ins.check(tmp_path, target)} == {"current"}
    base = tmp_path / ins.EXPORT_TARGETS[target].skills_dir
    edited = base / "sensoryforge-setup" / "SKILL.md"
    edited.write_text(edited.read_text("utf-8") + "\nedited by hand\n", "utf-8")
    (base / ins.GLOSSARY_NAME).unlink()
    states = dict(ins.check(tmp_path, target))
    assert states[edited] == "stale"
    assert states[base / ins.GLOSSARY_NAME] == "missing"
    assert list(states.values()).count("current") == len(states) - 2


def test_a_release_that_changes_a_skill_makes_the_old_export_stale(
    tmp_path, monkeypatch
):
    ins.install(tmp_path, "codex")
    changed = dict(ins.packaged_skills())["sensoryforge-setup"]
    real = Path.read_text

    def read_text(self, *args, **kwargs):
        text = real(self, *args, **kwargs)
        return text + "\nnew line in a later release\n" if self == changed else text

    monkeypatch.setattr(Path, "read_text", read_text)
    stale = [p for p, s in ins.check(tmp_path, "codex") if s == "stale"]
    assert [p.parent.name for p in stale] == ["sensoryforge-setup"]


@pytest.mark.parametrize("target", sorted(FOLDERS))
def test_generated_files_committed_in_this_repo_are_not_stale(target):
    """If a generated copy is checked in here (B10), it must match the source."""
    for path, state in ins.check(REPO, target):
        if path.is_file() and HEADER in path.read_text(encoding="utf-8"):
            assert state == "current", (
                f"{path.relative_to(REPO)} is stale: run "
                f"`sensoryforge agents export --target {target}`"
            )



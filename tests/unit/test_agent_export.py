"""Exporting the skills for other environments (roadmap B8).

The skills are one neutral source; ``sensoryforge agents export`` writes each tool's
native copy. These tests pin each target's folder (checked against the tool's own
documentation on ``FORMATS_CHECKED``), that every file is valid under the open Agent
Skills format and carries the do-not-edit header, that a stale file is caught, and
that the docs page and the prompts agree with the registry.
"""

import re
import sys
from pathlib import Path

import pytest

from sensoryforge.agents import install as ins
from sensoryforge.cli import main

REPO = Path(__file__).resolve().parents[2]
PAGE = REPO / "docs" / "user_guide" / "agent_export.md"

#: Where each tool reads a project's skills, as its documentation says (checked on
#: ``ins.FORMATS_CHECKED``). A change here is a change to what a user's tool reads.
FOLDERS = {
    "claude": ".claude/skills",
    "copilot": ".github/skills",
    "cursor": ".cursor/skills",
    "codex": ".agents/skills",
    "generic": "sensoryforge-agents",
}
NAME = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")  # no edge or doubled hyphen
HEADER = "Generated by `sensoryforge agents export --target"


def _front(text):
    lines = text.splitlines()
    assert lines[0] == "---"
    end = lines.index("---", 1)
    meta = {}
    for line in lines[1:end]:
        key, sep, value = line.partition(":")
        assert sep, line
        meta[key.strip()] = value.strip()
    return meta, "\n".join(lines[end + 1 :])


def run(monkeypatch, *args):
    monkeypatch.setattr(sys, "argv", ["sensoryforge", "agents", *args])
    return main()


# ------------------------------------------------------------------- the registry


def test_every_target_reads_the_folder_its_tool_documents():
    assert {
        n: t.skills_dir.as_posix() for n, t in ins.EXPORT_TARGETS.items()
    } == FOLDERS
    assert re.fullmatch(r"\d{4}-\d{2}-\d{2}", ins.FORMATS_CHECKED)
    for target in ins.EXPORT_TARGETS.values():
        assert target.source.startswith("https://"), target.name


def test_a_new_target_is_one_registration(monkeypatch):
    monkeypatch.setattr(ins, "EXPORT_TARGETS", dict(ins.EXPORT_TARGETS))
    new = ins.Target("mine", "My tool", Path(".mine") / "skills")
    assert ins.register_target(new) is new
    assert "mine" in ins.EXPORT_TARGETS
    with pytest.raises(ValueError, match="already registered"):
        ins.register_target(new)
    for bad in (Path("/abs"), Path("../out"), Path(".")):
        with pytest.raises(ValueError, match="inside the project"):
            ins.register_target(ins.Target("bad", "x", bad))


def test_an_unknown_target_is_refused_with_the_known_ones(tmp_path):
    with pytest.raises(ValueError, match="unknown target 'vim'.*claude"):
        ins.install(tmp_path, "vim")


# ----------------------------------------------------------- what is written


@pytest.mark.parametrize("target", sorted(FOLDERS))
def test_every_file_is_valid_headed_and_the_source_unchanged(tmp_path, target):
    written = ins.install(tmp_path, target)
    spec = ins.EXPORT_TARGETS[target]
    base = tmp_path / spec.skills_dir
    assert {s for _, s in written} == {"added"}
    names = [n for n, _ in ins.packaged_skills()]
    assert len(names) >= 10
    for name, source in ins.packaged_skills():
        text = (base / name / "SKILL.md").read_text(encoding="utf-8")
        meta, body = _front(text)
        # The open Agent Skills format, which every target's tool reads.
        assert set(meta) == {"name", "description"}, "only the fields all tools share"
        assert meta["name"] == name and NAME.match(name) and len(name) <= 64
        assert 1 <= len(meta["description"]) <= 1024, name
        # Front matter is first and the header comes right after it; taking the
        # header out gives the source file back, byte for byte.
        header = f"\n<!-- {HEADER} {target}`"
        assert header in text
        line = text[text.index(header) : text.index("-->\n", text.index(header)) + 4]
        assert text.replace(line, "", 1) == source.read_text(encoding="utf-8")
        assert _front(source.read_text(encoding="utf-8"))[0] == meta
    glossary = (base / ins.GLOSSARY_NAME).read_text(encoding="utf-8")
    assert glossary.startswith("<!-- " + HEADER)
    assert glossary.endswith(ins.packaged_glossary().read_text(encoding="utf-8"))
    extra = {p.name for p in base.iterdir()} - set(names) - {ins.GLOSSARY_NAME}
    assert extra == ({ins.INDEX_NAME} if spec.index else set())
    assert {p.name for p in tmp_path.iterdir()} == {spec.skills_dir.parts[0]}


def test_the_generic_index_lists_every_skill_with_its_first_sentence(tmp_path):
    ins.install(tmp_path, "generic")
    index = (tmp_path / "sensoryforge-agents" / ins.INDEX_NAME).read_text("utf-8")
    assert index.startswith("<!-- " + HEADER)
    for name, path in ins.packaged_skills():
        first = _front(path.read_text("utf-8"))[0]["description"].split(". ")[0]
        assert f"[{name}]({name}/SKILL.md) | {first.rstrip('.')}." in index
    assert "sensoryforge agents brief" in index


def test_a_skill_without_front_matter_is_refused():
    claude = ins.EXPORT_TARGETS["claude"]
    for bad in ("# no front matter\n", "---\nname: x\n", ""):
        with pytest.raises(ValueError, match="front matter"):
            ins.render_skill(bad, claude)


def test_a_second_export_changes_nothing_and_leaves_the_users_files(tmp_path):
    mine = tmp_path / ".cursor" / "rules" / "mine.mdc"
    mine.parent.mkdir(parents=True)
    mine.write_text("my rule", encoding="utf-8")
    other = tmp_path / ".cursor" / "skills" / "my-skill" / "SKILL.md"
    other.parent.mkdir(parents=True)
    other.write_text("my skill", encoding="utf-8")
    ins.install(tmp_path, "cursor")
    assert {s for _, s in ins.install(tmp_path, "cursor")} == {"unchanged"}
    assert mine.read_text(encoding="utf-8") == "my rule"
    assert other.read_text(encoding="utf-8") == "my skill"


# ------------------------------------------------------------------- staleness


@pytest.mark.parametrize("target", sorted(FOLDERS))
def test_check_finds_a_stale_or_missing_file_and_writes_nothing(tmp_path, target):
    assert {s for _, s in ins.check(tmp_path, target)} == {"missing"}
    assert not any(tmp_path.iterdir()), "check must not write"
    ins.install(tmp_path, target)
    assert {s for _, s in ins.check(tmp_path, target)} == {"current"}
    base = tmp_path / ins.EXPORT_TARGETS[target].skills_dir
    edited = base / "sensoryforge-setup" / "SKILL.md"
    edited.write_text(edited.read_text("utf-8") + "\nedited by hand\n", "utf-8")
    (base / ins.GLOSSARY_NAME).unlink()
    states = dict(ins.check(tmp_path, target))
    assert states[edited] == "stale"
    assert states[base / ins.GLOSSARY_NAME] == "missing"
    assert list(states.values()).count("current") == len(states) - 2


def test_a_release_that_changes_a_skill_makes_the_old_export_stale(
    tmp_path, monkeypatch
):
    ins.install(tmp_path, "codex")
    changed = dict(ins.packaged_skills())["sensoryforge-setup"]
    real = Path.read_text

    def read_text(self, *args, **kwargs):
        text = real(self, *args, **kwargs)
        return text + "\nnew line in a later release\n" if self == changed else text

    monkeypatch.setattr(Path, "read_text", read_text)
    stale = [p for p, s in ins.check(tmp_path, "codex") if s == "stale"]
    assert [p.parent.name for p in stale] == ["sensoryforge-setup"]


@pytest.mark.parametrize("target", sorted(FOLDERS))
def test_generated_files_committed_in_this_repo_are_not_stale(target):
    """If a generated copy is checked in here (B10), it must match the source."""
    for path, state in ins.check(REPO, target):
        if path.is_file() and HEADER in path.read_text(encoding="utf-8"):
            assert state == "current", (
                f"{path.relative_to(REPO)} is stale: run "
                f"`sensoryforge agents export --target {target}`"
            )


# ------------------------------------------------------------------ detection


def test_a_project_is_matched_by_the_folders_its_tools_document(tmp_path):
    none: dict = {}
    assert ins.detect_targets(tmp_path, none) == []
    for folder, want in [
        (".claude", "claude"),
        (".cursor", "cursor"),
        (".github/skills", "copilot"),
        (".agents", "codex"),
        (".codex", "codex"),
    ]:
        project = tmp_path / want / folder.strip(".").replace("/", "_")
        (project / folder).mkdir(parents=True)
        assert ins.detect_targets(project, none) == [want], folder
    assert ins.detect_targets(tmp_path, {"CLAUDECODE": "1"}) == ["claude"]
    both = tmp_path / "both"
    (both / ".cursor").mkdir(parents=True)
    (both / ".claude").mkdir()
    assert ins.detect_targets(both, none) == ["claude", "cursor"]
    assert "generic" not in ins.detect_targets(both, none)


def test_the_brief_finds_a_glossary_in_any_targets_folder(tmp_path):
    assert ins.glossary_path(tmp_path) == ins.packaged_glossary()
    ins.install(tmp_path, "cursor")
    assert (
        ins.glossary_path(tmp_path)
        == (tmp_path / ".cursor" / "skills" / ins.GLOSSARY_NAME).resolve()
    )


# ------------------------------------------------------------------------ the CLI


def test_export_writes_the_chosen_targets_folder(tmp_path, monkeypatch, capsys):
    assert (
        run(monkeypatch, "export", "--target", "copilot", "--dest", str(tmp_path)) == 0
    )
    out = capsys.readouterr().out
    assert "11 added" in out and str(tmp_path.resolve() / ".github" / "skills") in out
    assert (
        tmp_path / ".github" / "skills" / "sensoryforge-setup" / "SKILL.md"
    ).is_file()
    assert not (tmp_path / ".claude").exists()


def test_install_is_export_to_claude(tmp_path, monkeypatch):
    one, two = tmp_path / "one", tmp_path / "two"
    one.mkdir(), two.mkdir()
    assert run(monkeypatch, "install", "--dest", str(one)) == 0
    assert run(monkeypatch, "export", "--target", "claude", "--dest", str(two)) == 0
    for name, _ in ins.packaged_skills():
        rel = Path(".claude") / "skills" / name / "SKILL.md"
        assert (one / rel).read_bytes() == (two / rel).read_bytes()


def test_auto_picks_the_one_environment_found_and_refuses_to_guess(
    tmp_path, monkeypatch, capsys
):
    monkeypatch.delenv("CLAUDECODE", raising=False)
    project = tmp_path / "p"
    (project / ".cursor").mkdir(parents=True)
    assert run(monkeypatch, "export", "--dest", str(project)) == 0
    assert (project / ".cursor" / "skills" / ins.GLOSSARY_NAME).is_file()
    assert "Target cursor" in capsys.readouterr().out
    (tmp_path / "empty").mkdir()
    (tmp_path / "two" / ".cursor").mkdir(parents=True)
    (tmp_path / "two" / ".agents").mkdir()
    for name in ("empty", "two"):
        assert run(monkeypatch, "export", "--dest", str(tmp_path / name)) == 1
        err = capsys.readouterr().err
        assert "cannot tell which environment" in err and "--target" in err
    assert not (tmp_path / "empty" / ".cursor").exists()
    assert not (tmp_path / "two" / ".cursor" / "skills").exists()


def test_export_check_exits_nonzero_until_the_files_are_current(
    tmp_path, monkeypatch, capsys
):
    args = ("export", "--target", "codex", "--dest", str(tmp_path))
    assert run(monkeypatch, *args, "--check") == 1
    captured = capsys.readouterr()
    assert "missing" in captured.out and "agents export --target codex" in captured.err
    assert not (tmp_path / ".agents").exists()
    assert run(monkeypatch, *args) == 0
    capsys.readouterr()
    assert run(monkeypatch, *args, "--check") == 0
    assert "11 current" in capsys.readouterr().out
    (tmp_path / ".agents" / "skills" / ins.GLOSSARY_NAME).write_text("x", "utf-8")
    assert run(monkeypatch, *args, "--check") == 1
    assert "stale" in capsys.readouterr().out


def test_export_refuses_a_missing_folder(tmp_path, monkeypatch, capsys):
    argv = ("export", "--target", "cursor", "--dest", str(tmp_path / "missing"))
    assert run(monkeypatch, *argv) == 1
    assert "is not a folder" in capsys.readouterr().err


def test_generic_export_says_nothing_reads_it_by_itself(tmp_path, monkeypatch, capsys):
    argv = ("export", "--target", "generic", "--dest", str(tmp_path))
    assert run(monkeypatch, *argv) == 0
    assert "agents prompt generic" in capsys.readouterr().out


def test_prompt_prints_the_shipped_files(monkeypatch, capsys):
    for name in ("install", "generic"):
        assert run(monkeypatch, "prompt", name) == 0
        assert capsys.readouterr().out == ins.packaged_prompt(name).read_text("utf-8")
    assert run(monkeypatch, "prompt") == 0
    assert capsys.readouterr().out == ins.packaged_prompt("install").read_text("utf-8")
    with pytest.raises(SystemExit):
        run(monkeypatch, "prompt", "nope")
    with pytest.raises(ValueError, match="no prompt named"):
        ins.packaged_prompt("nope")


# --------------------------------------------------- the prompts and the docs page


def test_the_install_prompt_has_a_row_for_every_target_but_generic():
    text = ins.packaged_prompt("install").read_text("utf-8")
    rows = set(re.findall(r"agents export --target (\w+)`", text))
    assert rows == set(FOLDERS) - {"generic"}
    assert "agents prompt generic" in text


def test_the_generic_prompt_writes_no_format_it_has_not_found_documented():
    text = " ".join(ins.packaged_prompt("generic").read_text("utf-8").split())
    assert "export --target generic" in text and "Never guess a format" in text
    assert "never memory alone" in text
    assert "ask them where the files should go" in text


def test_the_docs_page_carries_the_prompts_and_every_target():
    page = PAGE.read_text(encoding="utf-8")
    for name in ("install", "generic"):
        body = ins.packaged_prompt(name).read_text("utf-8").rstrip()
        assert f"```text\n{body}\n```" in page, f"docs page is behind {name}.md"
    for name, target in ins.EXPORT_TARGETS.items():
        assert f"| `{name}` | `{target.skills_dir.as_posix()}/` |" in page
        assert target.source in page
    assert ins.FORMATS_CHECKED in page

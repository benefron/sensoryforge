"""Generate `docs/reference/benchmarks.md` from a benchmark JSON file.

Never hand-edit `docs/reference/benchmarks.md` -- it is regenerated by this
module (invoked by `run_benchmarks.py`, or standalone via
`python -m benchmarks.generate_table <json>`).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Dict


def _fmt_ms(seconds: float) -> str:
    return f"{seconds * 1000:.2f}"


def generate(data: Dict[str, Any], out_path: Path) -> None:
    env = data["environment"]
    lines = []
    lines.append("# Benchmarks")
    lines.append("")
    lines.append(
        "This page is generated by `benchmarks/generate_table.py` from "
        "`benchmarks/results/latest.json`. **Do not hand-edit it** -- regenerate with:"
    )
    lines.append("")
    lines.append("```bash")
    lines.append("export OMP_NUM_THREADS=2 MKL_NUM_THREADS=2 QT_QPA_PLATFORM=offscreen")
    lines.append("python -m benchmarks.run_benchmarks")
    lines.append("```")
    lines.append("")
    lines.append(
        f"Measured on: **{env['machine']}** / **{env['cpu']}**, generated "
        f"{data['generated_at']}."
    )
    lines.append("")
    lines.append("| | |")
    lines.append("|---|---|")
    lines.append(f"| Python | {env['python']} |")
    lines.append(f"| torch | {env['torch']} |")
    lines.append(f"| sensoryforge | {env['sensoryforge']} |")
    lines.append(
        f"| OMP_NUM_THREADS / MKL_NUM_THREADS | {env['omp_num_threads']} / {env['mkl_num_threads']} |"
    )
    lines.append(f"| seed | {env['seed']} |")
    lines.append("")
    lines.append("## What these numbers are, and what they replace")
    lines.append("")
    lines.append(
        "Every cell below is repeated (one discarded warm-up plus N timed repeats, N shown "
        "in the table) in its own fresh subprocess, and the table reports the **median and "
        "the observed min-max spread**, not a single sample. This exists because the project "
        "previously had no way to tell a real regression from run-to-run noise: the whole-suite "
        "memory watchdog (finding F-056, guardrail 6 of Phase 2) measured the *same commit* at "
        "873 MB on one run and 1,517 MB on another. A single number here would be just as "
        "unusable; the spread column is the point."
    )
    lines.append("")
    lines.append(
        "Build time (constructing `SimulationEngine` -- grids and receptive-field banks) and "
        "run time (`engine.run()`) are reported separately because they scale differently: "
        "build time grows with grid size and neuron count, run time grows with grid size, "
        "neuron count *and* simulated duration."
    )
    lines.append("")
    lines.append("## Memory: what is and is not captured")
    lines.append("")
    lines.append(
        "`peak_rss_mb` is the peak of (subprocess RSS + all its children's RSS), sampled "
        "every 50 ms for the subprocess's whole lifetime -- the same ps-based sum-of-RSS "
        "technique as the Phase 1 memory watchdog "
        "(`docs/development/handover/phase1_tasks.md` appendix), applied to one benchmark "
        "cell instead of a whole test suite."
    )
    lines.append("")
    lines.append("This measurement:")
    lines.append("")
    lines.append(
        "- **Does** capture the peak of the whole worker process, including the warm-up "
        "iteration, Python/torch import, and every timed repeat -- it is a realistic "
        "peak for running that cell, not an isolated allocation figure."
    )
    lines.append(
        "- **Does not** separate build-phase memory from run-phase memory (unlike wall-clock, "
        "which is timed separately in-process); a 50 ms sampling interval also means a peak "
        "narrower than 50 ms can be missed."
    )
    lines.append(
        "- **Does not** use `tracemalloc`: SensoryForge's tensors are mostly torch-allocated "
        "(C++/native memory), which `tracemalloc` does not see, so it would under-report "
        "the figure that actually matters here. `resource.getrusage(RUSSELF_CHILDREN)` was "
        "considered and rejected for the same reason `ps`-sampling was kept: on macOS "
        "`ru_maxrss` is only available for the *current* process's own peak, not a child "
        "subprocess's, and the harness deliberately runs each cell in a fresh subprocess "
        "so a clean-slate peak is comparable across cells."
    )
    lines.append(
        "- **Is noisy in the same way finding F-056 describes**, at a smaller scale: this "
        "machine slept and independently ran low on memory overnight during this wave's "
        "own measurement runs, and readings taken across such an event are not comparable "
        "(see `started_at`/`finished_at` timestamps in the JSON). Treat `peak_rss_mb` as a "
        "smoke alarm -- notice if it doubles -- not a precise gauge, exactly per guardrail 6."
    )
    lines.append("")
    lines.append("## Results")
    lines.append("")
    lines.append(
        "| Cell | Grid | SA x RA / row | Duration (ms) | Device | N | "
        "Build median (ms) | Build spread (ms) | Run median (ms) | Run spread (ms) | Peak RSS (MB) |"
    )
    lines.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for c in data["cells"]:
        cell = c["cell"]
        lines.append(
            "| {name} | {rows}x{cols} | {sa} x {ra} | {dur:.0f} | {dev} | {n} | "
            "{bmed} | {bspread} | {rmed} | {rspread} | {rss} |".format(
                name=cell["name"],
                rows=cell["rows"],
                cols=cell["cols"],
                sa=cell["neurons_per_row_sa"],
                ra=cell["neurons_per_row_ra"],
                dur=cell["duration_ms"],
                dev=cell["device"],
                n=c["build"]["n"],
                bmed=_fmt_ms(c["build"]["median_s"]),
                bspread=_fmt_ms(c["build"]["spread_s"]),
                rmed=_fmt_ms(c["run"]["median_s"]),
                rspread=_fmt_ms(c["run"]["spread_s"]),
                rss=c["peak_rss_mb"],
            )
        )
    lines.append("")
    lines.append(
        "`large_80x80` is the cell required by the Wave T spec (an 80x80 grid with both "
        "SA and RA populations); `smoke_10x10` is the fast smoke-test cell."
    )
    lines.append("")
    lines.append("## Raw samples")
    lines.append("")
    lines.append(
        "Full per-repeat timings (not just median/min/max) are in "
        "`benchmarks/results/latest.json` under each cell's `raw_build_s`/`raw_run_s`."
    )
    lines.append("")
    lines.append("## CI regression guard")
    lines.append("")
    lines.append(
        "`.github/workflows/benchmarks.yml` runs the `ci_guard` cell (same shape as "
        "`smoke_10x10`) on every push and pull request via "
        "`python -m benchmarks.check_regression`, and fails if the engine has become "
        "more than **3.0x** slower than the baseline in "
        "`benchmarks/results/ci_baseline.json`."
    )
    lines.append("")
    lines.append(
        "**What is compared.** Not raw milliseconds. The baseline was measured on an "
        "Apple M3 Pro laptop and the guard runs on a GitHub Linux runner, and those "
        "machines take different times for the same code; that difference is a fixed "
        "offset, not noise, so a raw comparison would pass or fail on hardware alone. "
        "Each run therefore also times a fixed reference kernel, interleaved with the "
        "engine in the same process, and the guard compares engine time divided by "
        "reference time, now against then. A uniformly slower machine cancels out; a "
        "slower engine does not."
    )
    lines.append("")
    lines.append(
        "**Evidence that it works, on real hardware.** Pinning the run to this chip's "
        "slower efficiency cores (`taskpolicy -b`) raised the engine's raw time 4.56x, "
        "from 40.08 ms to 182.68 ms, which would fail an uncalibrated 3.0x guard with "
        "no code changed. The calibrated factor was 1.05x and the guard passed. With a "
        "150 ms sleep injected into `SimulationEngine.run`, the calibrated factor was "
        "5.30x and the guard failed. Across six baseline runs the ratio varied 3.5%, "
        "tighter than the engine's 8.0% or the reference's 8.6% alone, because a run "
        "slowed by machine state slows both."
    )
    lines.append("")
    lines.append(
        "**What it will not catch.** A regression smaller than about 3x on this cell "
        "passes: an engine made 50% or 100% slower gets through. And efficiency and "
        "performance cores share an architecture and a BLAS library, so moving to x86 "
        "CI hardware can shift the ratio more than the experiment above did; the 3.0x "
        "factor is generous partly for that reason. Measured on its first GitHub Linux "
        "x86_64 run: raw engine time 1.50x the baseline, reference kernel 1.60x, "
        "calibrated factor 0.94x, a shift of about 6 percent. See "
        "`benchmarks/check_regression.py`'s docstring for the full reasoning."
    )
    lines.append("")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n")


def main(argv=None) -> int:
    argv = argv if argv is not None else sys.argv[1:]
    if len(argv) != 1:
        print(
            "usage: python -m benchmarks.generate_table <results.json>", file=sys.stderr
        )
        return 2
    data = json.loads(Path(argv[0]).read_text())
    out_path = (
        Path(__file__).resolve().parent.parent / "docs" / "reference" / "benchmarks.md"
    )
    generate(data, out_path)
    print(f"Wrote {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
